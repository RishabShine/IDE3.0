"""Simulated coding assistant for the proposal-v1 loop.

This stands in for a real IDE assistant (Cursor / Claude Code / Copilot). It
connects to the IDE3 MCP server over stdio and, for every feature request, it
is *forced* to call ``capture_intent`` first and wait. Only when the tool
returns ``approved`` does it "generate code" (here: write a stub file into
``test-v1/generated/``). On ``rejected`` it asks how to revise instead.

Run it, then open the IDE3 panel (or edit ``.ide3/proposal.json``) to approve:

    python test-v1/agent.py "add a dark mode toggle to the settings page"
"""

from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client

# --- resolve repo-relative paths -----------------------------------------
TEST_DIR = Path(__file__).resolve().parent            # .../test-v1
REPO_ROOT = TEST_DIR.parent
MCP_DIR = REPO_ROOT / "src" / "ide3-mcp"
VENV_PYTHON = MCP_DIR / ".venv" / "bin" / "python"
SERVER_SCRIPT = MCP_DIR / "server.py"
GENERATED_DIR = TEST_DIR / "generated"


class SimulatedCodingAssistant:
    """A minimal agent that must clear requirements before writing code."""

    def __init__(self, workspace: Path) -> None:
        self._workspace = workspace
        self._server_params = StdioServerParameters(
            command=str(VENV_PYTHON),
            args=[str(SERVER_SCRIPT)],
            env={"IDE3_WORKSPACE": str(workspace)},
        )

    async def handle_request(self, user_query: str) -> None:
        print(f"\n[assistant] user asked: {user_query!r}")
        print("[assistant] calling capture_intent and waiting for your review...")
        print(f"[assistant] review at: {self._workspace / '.ide3' / 'proposal.json'}")
        print("[assistant] (approve/reject in the IDE3 panel)\n")

        result = await self._capture_intent(user_query)
        status = result.get("status")

        if status == "approved":
            self._on_approved(result)
        elif status == "rejected":
            self._on_rejected(result)
        elif status == "timeout":
            print(f"[assistant] timed out: {result.get('detail')}")
        else:
            print(f"[assistant] unexpected result: {result}")

    async def _capture_intent(self, user_query: str) -> dict:
        async with stdio_client(self._server_params) as (read, write):
            async with ClientSession(read, write) as session:
                await session.initialize()
                response = await session.call_tool(
                    "capture_intent", {"user_query": user_query}
                )
                return self._unwrap(response)

    @staticmethod
    def _unwrap(response) -> dict:
        """Extract the tool's JSON payload from an MCP CallToolResult."""
        if response.structured_content:
            return response.structured_content
        for block in response.content:
            text = getattr(block, "text", None)
            if text:
                return json.loads(text)
        return {}

    def _on_approved(self, result: dict) -> None:
        print("[assistant] requirements APPROVED. Generating code...\n")
        for req in result.get("requirements", []):
            print(f"    - {req['id']}: {req['title']}")
        path = self._write_stub(result)
        print(f"\n[assistant] code generated at: {path}")

    def _on_rejected(self, result: dict) -> None:
        print("[assistant] requirements REJECTED. No code generated.")
        print("[assistant] How would you like to revise the request?")

    def _write_stub(self, result: dict) -> Path:
        """Write a dummy implementation reflecting the approved requirements."""
        GENERATED_DIR.mkdir(parents=True, exist_ok=True)
        proposal_id = result.get("proposal_id", "unknown")
        out = GENERATED_DIR / f"{proposal_id}.py"

        lines = [
            '"""Auto-generated stub for an APPROVED IDE3 proposal.',
            "",
            f"Proposal: {proposal_id}",
            f"Request:  {result.get('user_query', '')}",
            '"""',
            "",
            "",
            "def feature():",
            '    """Implements the approved functional requirements:',
        ]
        for req in result.get("requirements", []):
            lines.append(f"    - {req['id']}: {req['title']} - {req['description']}")
        lines += ['    Subject to quality constraints:']
        for qc in result.get("quality_constraints", []):
            lines.append(f"    - {qc['id']}: {qc['title']} - {qc['description']}")
        lines += [
            '    """',
            "    raise NotImplementedError('stub generated by proposal-v1 loop')",
            "",
        ]
        out.write_text("\n".join(lines), encoding="utf-8")
        return out


async def _amain(user_query: str) -> None:
    assistant = SimulatedCodingAssistant(workspace=TEST_DIR)
    await assistant.handle_request(user_query)


def main() -> None:
    query = " ".join(sys.argv[1:]).strip()
    if not query:
        query = "add a dark mode toggle to the settings page"
    try:
        asyncio.run(_amain(query))
    except KeyboardInterrupt:
        print("\n[assistant] cancelled — no code generated.")


if __name__ == "__main__":
    main()
